-- Point-in-Time Point-of-Sale Analytics Query
  
SELECT
    f.TRANSACTION_ID,
    f.TRANSACTION_DATE,
    c101.CUSTOMER_ID,
    c101.CUSTOMER_NAME,
    cur.CITY                        AS CURRENT_CITY,
    c101.HISTORICAL_MEMBERSHIP      AS MEMBERSHIP_AT_PURCHASE,
    c101.SEGMENT                    AS SEGMENT_AT_PURCHASE,
    s.STORE_NAME,
    p.PRODUCT_NAME,
    f.TOTAL_AMOUNT
FROM FACT_SALES f
JOIN DIM_CUSTOMER_HYBRID c101
    ON f.TRANSACTION_DATE BETWEEN c101.EFFECTIVE_DATE AND c101.EXPIRY_DATE
   AND c101.CUSTOMER_ID = 101
JOIN DIM_CUSTOMER_HYBRID cur
    ON cur.CUSTOMER_ID = 101 AND cur.IS_CURRENT = TRUE
JOIN DIM_STORE s   ON f.STORE_KEY   = s.STORE_KEY
JOIN DIM_PRODUCT p ON f.PRODUCT_KEY = p.PRODUCT_KEY
WHERE f.CUSTOMER_KEY IN (
    SELECT CUSTOMER_KEY FROM DIM_CUSTOMER_HYBRID WHERE CUSTOMER_ID = 101
)
ORDER BY f.TRANSACTION_DATE;

