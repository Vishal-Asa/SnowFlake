CREATE OR REPLACE FILE FORMAT CSV_FF
    TYPE = 'CSV'
    FIELD_DELIMITER = ','
    SKIP_HEADER = 1
    FIELD_OPTIONALLY_ENCLOSED_BY = '"'
    NULL_IF = ('NULL', 'null', '');

CREATE OR REPLACE STAGE RETAIL_STAGE
    FILE_FORMAT = CSV_FF;

-- Create Store Conformed Dimension Table (DIM_STORE)
  
CREATE OR REPLACE TABLE DIM_STORE (
    STORE_KEY      NUMBER AUTOINCREMENT START 1 INCREMENT 1 PRIMARY KEY,
    STORE_ID       NUMBER,
    STORE_NAME     VARCHAR(100),
    CITY           VARCHAR(50),
    STATE          VARCHAR(50),
    STORE_MANAGER  VARCHAR(100)
);



-- Create Product Dimension Table (DIM_PRODUCT)

CREATE OR REPLACE TABLE DIM_PRODUCT (
    PRODUCT_KEY    NUMBER AUTOINCREMENT START 1 INCREMENT 1 PRIMARY KEY,
    PRODUCT_ID     NUMBER,
    PRODUCT_NAME   VARCHAR(100),
    CATEGORY       VARCHAR(50),
    UNIT_PRICE     NUMBER(10,2)
);


-- Create Hybrid Customer Dimension Table (DIM_CUSTOMER_HYBRID)

CREATE OR REPLACE TABLE DIM_CUSTOMER_HYBRID (
    CUSTOMER_KEY            NUMBER AUTOINCREMENT START 1 INCREMENT 1 PRIMARY KEY,
    CUSTOMER_ID             NUMBER,
    CUSTOMER_NAME           VARCHAR(100),
    CITY                    VARCHAR(50),   -- current city, globally synced
    PREVIOUS_CITY           VARCHAR(50),   -- SCD Type 3
    STATE                   VARCHAR(50),
    CURRENT_MEMBERSHIP      VARCHAR(30),   -- SCD Type 6, globally synced
    PREVIOUS_MEMBERSHIP     VARCHAR(30),   -- SCD Type 6 / Type 3 column
    HISTORICAL_MEMBERSHIP   VARCHAR(30),   -- SCD Type 6 / Type 2 row slice
    SEGMENT                 VARCHAR(30),   -- SCD Type 2, row versioned
    EFFECTIVE_DATE          DATE,
    EXPIRY_DATE             DATE,
    IS_CURRENT              BOOLEAN
);


