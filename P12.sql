-- Execute Multi-Attribute Customer Updates
  
CREATE OR REPLACE TABLE CUSTOMER_UPDATES (
    CUSTOMER_ID     NUMBER,
    CUSTOMER_NAME   VARCHAR(100),
    CITY            VARCHAR(50),
    STATE           VARCHAR(50),
    MEMBERSHIP      VARCHAR(30),
    SEGMENT         VARCHAR(30),
    EFFECTIVE_DATE  DATE
);

COPY INTO CUSTOMER_UPDATES (CUSTOMER_ID, CUSTOMER_NAME, CITY, STATE, MEMBERSHIP, SEGMENT, EFFECTIVE_DATE)
FROM @RETAIL_STAGE/customer_updates.csv
FILE_FORMAT = (FORMAT_NAME = CSV_FF)
ON_ERROR = 'ABORT_STATEMENT';

-- Step 1: Expire active records (one statement per customer) 

UPDATE DIM_CUSTOMER_HYBRID d
SET d.EXPIRY_DATE = DATEADD(DAY, -1, u.EFFECTIVE_DATE),
    d.IS_CURRENT  = FALSE
FROM CUSTOMER_UPDATES u
WHERE d.CUSTOMER_ID = u.CUSTOMER_ID
  AND d.IS_CURRENT  = TRUE
  AND d.CUSTOMER_ID = 101;

UPDATE DIM_CUSTOMER_HYBRID d
SET d.EXPIRY_DATE = DATEADD(DAY, -1, u.EFFECTIVE_DATE),
    d.IS_CURRENT  = FALSE
FROM CUSTOMER_UPDATES u
WHERE d.CUSTOMER_ID = u.CUSTOMER_ID
  AND d.IS_CURRENT  = TRUE
  AND d.CUSTOMER_ID = 103;

UPDATE DIM_CUSTOMER_HYBRID d
SET d.EXPIRY_DATE = DATEADD(DAY, -1, u.EFFECTIVE_DATE),
    d.IS_CURRENT  = FALSE
FROM CUSTOMER_UPDATES u
WHERE d.CUSTOMER_ID = u.CUSTOMER_ID
  AND d.IS_CURRENT  = TRUE
  AND d.CUSTOMER_ID = 104;

-- Step 2: Insert new active row versions (single statement, 3 rows) 

INSERT INTO DIM_CUSTOMER_HYBRID
    (CUSTOMER_ID, CUSTOMER_NAME, CITY, PREVIOUS_CITY, STATE,
     CURRENT_MEMBERSHIP, PREVIOUS_MEMBERSHIP, HISTORICAL_MEMBERSHIP,
     SEGMENT, EFFECTIVE_DATE, EXPIRY_DATE, IS_CURRENT)
SELECT
    u.CUSTOMER_ID, u.CUSTOMER_NAME,
    u.CITY,
    old.CITY AS PREVIOUS_CITY,
    u.STATE,
    u.MEMBERSHIP AS CURRENT_MEMBERSHIP,
    old.CURRENT_MEMBERSHIP AS PREVIOUS_MEMBERSHIP,
    u.MEMBERSHIP AS HISTORICAL_MEMBERSHIP,
    u.SEGMENT,
    u.EFFECTIVE_DATE, DATE '9999-12-31', TRUE
FROM CUSTOMER_UPDATES u
JOIN DIM_CUSTOMER_HYBRID old
    ON old.CUSTOMER_ID = u.CUSTOMER_ID
   AND old.IS_CURRENT  = FALSE
   AND old.EXPIRY_DATE = DATEADD(DAY, -1, u.EFFECTIVE_DATE);

--  Step 3: Synchronize CURRENT_MEMBERSHIP, PREVIOUS_MEMBERSHIP,
--              CITY, STATE across ALL rows per changed customer 

UPDATE DIM_CUSTOMER_HYBRID d
SET d.CITY                = cur.CITY,
    d.STATE               = cur.STATE,
    d.CURRENT_MEMBERSHIP  = cur.CURRENT_MEMBERSHIP,
    d.PREVIOUS_MEMBERSHIP = cur.PREVIOUS_MEMBERSHIP
FROM (
    SELECT CITY, STATE, CURRENT_MEMBERSHIP, PREVIOUS_MEMBERSHIP
    FROM DIM_CUSTOMER_HYBRID
    WHERE CUSTOMER_ID = 101 AND IS_CURRENT = TRUE
) cur
WHERE d.CUSTOMER_ID = 101;


UPDATE DIM_CUSTOMER_HYBRID d
SET d.CITY                = cur.CITY,
    d.STATE               = cur.STATE,
    d.CURRENT_MEMBERSHIP  = cur.CURRENT_MEMBERSHIP,
    d.PREVIOUS_MEMBERSHIP = cur.PREVIOUS_MEMBERSHIP
FROM (
    SELECT CITY, STATE, CURRENT_MEMBERSHIP, PREVIOUS_MEMBERSHIP
    FROM DIM_CUSTOMER_HYBRID
    WHERE CUSTOMER_ID = 103 AND IS_CURRENT = TRUE
) cur
WHERE d.CUSTOMER_ID = 103;

UPDATE DIM_CUSTOMER_HYBRID d
SET d.CITY                = cur.CITY,
    d.STATE               = cur.STATE,
    d.CURRENT_MEMBERSHIP  = cur.CURRENT_MEMBERSHIP,
    d.PREVIOUS_MEMBERSHIP = cur.PREVIOUS_MEMBERSHIP
FROM (
    SELECT CITY, STATE, CURRENT_MEMBERSHIP, PREVIOUS_MEMBERSHIP
    FROM DIM_CUSTOMER_HYBRID
    WHERE CUSTOMER_ID = 104 AND IS_CURRENT = TRUE
) cur
WHERE d.CUSTOMER_ID = 104;


