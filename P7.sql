CREATE OR REPLACE TABLE FACT_ADMISSION (
    ADMISSION_KEY   NUMBER(38,0) PRIMARY KEY,
    PATIENT_KEY     NUMBER(38,0),
    DOCTOR_KEY      NUMBER(38,0),
    HOSPITAL_KEY    NUMBER(38,0),
    DEPARTMENT_KEY  NUMBER(38,0),
    DATE_KEY        NUMBER(38,0),
    ADMISSION_COUNT NUMBER(38,0),
    LENGTH_OF_STAY  NUMBER(38,0),

    CONSTRAINT FK_ADMISSION_PATIENT
        FOREIGN KEY (PATIENT_KEY) REFERENCES DIM_PATIENT(PATIENT_KEY),

    CONSTRAINT FK_ADMISSION_DOCTOR
        FOREIGN KEY (DOCTOR_KEY) REFERENCES DIM_DOCTOR(DOCTOR_KEY),

    CONSTRAINT FK_ADMISSION_HOSPITAL
        FOREIGN KEY (HOSPITAL_KEY) REFERENCES DIM_HOSPITAL(HOSPITAL_KEY),

    CONSTRAINT FK_ADMISSION_DEPARTMENT
        FOREIGN KEY (DEPARTMENT_KEY) REFERENCES DIM_DEPARTMENT(DEPARTMENT_KEY),

    CONSTRAINT FK_ADMISSION_DATE
        FOREIGN KEY (DATE_KEY) REFERENCES DIM_DATE(DATE_KEY)
);


-- FACT_ADMISSION GRAIN

-- LOAD FACT_ADMISSION

INSERT INTO FACT_ADMISSION
SELECT
    ROW_NUMBER() OVER (ORDER BY A.ADMISSION_ID) AS ADMISSION_KEY,
    P.PATIENT_KEY,
    D.DOCTOR_KEY,
    H.HOSPITAL_KEY,
    DP.DEPARTMENT_KEY,
    DT.DATE_KEY,
    1 AS ADMISSION_COUNT,
    DATEDIFF(DAY, A.ADMISSION_DATE, A.DISCHARGE_DATE) AS LENGTH_OF_STAY
FROM RAW_ADMISSIONS A
JOIN DIM_PATIENT P
    ON A.PATIENT_ID = P.PATIENT_ID
JOIN DIM_DOCTOR D
    ON A.DOCTOR_ID = D.DOCTOR_ID
JOIN DIM_HOSPITAL H
    ON A.HOSPITAL_ID = H.HOSPITAL_ID
JOIN DIM_DEPARTMENT DP
    ON A.DEPARTMENT_ID = DP.DEPARTMENT_ID
JOIN DIM_DATE DT
    ON A.ADMISSION_DATE = DT.FULL_DATE;


