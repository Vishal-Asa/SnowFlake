-- Monthly admissions
SELECT
    TO_CHAR(DD.FULL_DATE, 'YYYY-MM') AS MONTH,
    SUM(F.ADMISSION_COUNT) AS TOTAL_ADMISSIONS
FROM FACT_ADMISSION F
JOIN DIM_DATE DD
    ON F.DATE_KEY = DD.DATE_KEY
