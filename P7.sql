-- FACT_BILLING GRAIN

 INSERT INTO FACT_BILLING
 SELECT
     ROW_NUMBER() OVER (ORDER BY B.BILLING_ID) AS BILLING_KEY,
     P.PATIENT_KEY,
     D.DOCTOR_KEY,
     H.HOSPITAL_KEY,
     DP.DEPARTMENT_KEY,
     T.TREATMENT_KEY,
     DD.DATE_KEY,
     B.QUANTITY,
     B.TREATMENT_AMOUNT,
     B.DISCOUNT,
     B.TREATMENT_AMOUNT - B.DISCOUNT AS NET_AMOUNT
 FROM RAW_BILLING B
 JOIN DIM_PATIENT P
     ON B.PATIENT_ID = P.PATIENT_ID
 JOIN DIM_DOCTOR D
     ON B.DOCTOR_ID = D.DOCTOR_ID
 JOIN DIM_HOSPITAL H
     ON B.HOSPITAL_ID = H.HOSPITAL_ID
 JOIN DIM_DEPARTMENT DP
     ON B.DEPARTMENT_ID = DP.DEPARTMENT_ID
 JOIN DIM_TREATMENT T
     ON B.TREATMENT_ID = T.TREATMENT_ID
 JOIN DIM_DATE DD
      ON B.BILLING_DATE = DD.FULL_DATE;


