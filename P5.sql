-- Phase 7

-- Customer-wise Sales Report
SELECT C.CUSTOMER_ID, C.CUSTOMER_NAME, C.MEMBERSHIP, SUM(F.QUANTITY) AS TOTAL_QUANTITY, SUM(F.TOTAL_AMOUNT) AS TOTAL_SALES
FROM FACT_SALES F
JOIN DIM_CUSTOMER C
    ON F.CUSTOMER_ID = C.CUSTOMER_ID
GROUP BY C.CUSTOMER_ID, C.CUSTOMER_NAME, C.MEMBERSHIP
ORDER BY TOTAL_SALES DESC;

-- Product-wise Revenue Report
SELECT P.PRODUCT_ID, P.PRODUCT_NAME, P.CATEGORY, P.BRAND, SUM(F.QUANTITY) AS TOTAL_QUANTITY, SUM(F.TOTAL_AMOUNT) AS TOTAL_REVENUE
FROM FACT_SALES F
JOIN DIM_PRODUCT P
    ON F.PRODUCT_ID = P.PRODUCT_ID
GROUP BY P.PRODUCT_ID, P.PRODUCT_NAME, P.CATEGORY, P.BRAND
ORDER BY TOTAL_REVENUE DESC;

-- Branch-wise Revenue Report
SELECT B.BRANCH_ID, B.BRANCH_NAME, B.CITY, B.STATE, B.REGION,
    SUM(F.QUANTITY) AS TOTAL_QUANTITY,
    SUM(F.TOTAL_AMOUNT) AS TOTAL_REVENUE
FROM FACT_SALES F
JOIN DIM_BRANCH B
    ON F.BRANCH_ID = B.BRANCH_ID
GROUP BY B.BRANCH_ID, B.BRANCH_NAME, B.CITY, B.STATE, B.REGION
ORDER BY TOTAL_REVENUE DESC;

-- State-wise Revenue Report
SELECT B.STATE,
    SUM(F.QUANTITY) AS TOTAL_QUANTITY,
    SUM(F.TOTAL_AMOUNT) AS TOTAL_REVENUE
FROM FACT_SALES F
JOIN DIM_BRANCH B
    ON F.BRANCH_ID = B.BRANCH_ID
GROUP BY B.STATE
ORDER BY TOTAL_REVENUE DESC;

-- Monthly Revenue Report
SELECT D.YEAR, D.MONTH,
    SUM(F.TOTAL_AMOUNT) AS TOTAL_REVENUE
FROM FACT_SALES F
JOIN DIM_DATE D
    ON F.DATE_ID = D.DATE_ID
GROUP BY D.YEAR, D.MONTH
ORDER BY D.YEAR, MIN(D.DATE);

-- Quarterly Revenue Report
SELECT D.YEAR, D.QUARTER,
    SUM(F.TOTAL_AMOUNT) AS TOTAL_REVENUE
FROM FACT_SALES F
JOIN DIM_DATE D
    ON F.DATE_ID = D.DATE_ID
GROUP BY D.YEAR, D.QUARTER
ORDER BY
    D.YEAR,
    D.QUARTER;

-- Top 10 Customers
SELECT C.CUSTOMER_ID, C.CUSTOMER_NAME,
    SUM(F.TOTAL_AMOUNT) AS TOTAL_REVENUE
FROM FACT_SALES F
JOIN DIM_CUSTOMER C
    ON F.CUSTOMER_ID = C.CUSTOMER_ID
GROUP BY C.CUSTOMER_ID, C.CUSTOMER_NAME
ORDER BY TOTAL_REVENUE DESC
LIMIT 10;

-- Top 10 Products
SELECT P.PRODUCT_ID, P.PRODUCT_NAME, P.CATEGORY,
    SUM(F.TOTAL_AMOUNT) AS TOTAL_REVENUE
FROM FACT_SALES F
JOIN DIM_PRODUCT P
    ON F.PRODUCT_ID = P.PRODUCT_ID
GROUP BY P.PRODUCT_ID, P.PRODUCT_NAME, P.CATEGORY
ORDER BY TOTAL_REVENUE DESC
LIMIT 10;

-- Top 10 Performing Branches
SELECT
    B.BRANCH_ID, B.BRANCH_NAME, B.STATE, B.REGION,
    SUM(F.TOTAL_AMOUNT) AS TOTAL_REVENUE
FROM FACT_SALES F
JOIN DIM_BRANCH B
    ON F.BRANCH_ID = B.BRANCH_ID
GROUP BY B.BRANCH_ID, B.BRANCH_NAME, B.STATE, B.REGION
ORDER BY TOTAL_REVENUE DESC
LIMIT 10;

-- Category-wise Revenue
SELECT P.CATEGORY,
    SUM(F.QUANTITY) AS TOTAL_QUANTITY,
    SUM(F.TOTAL_AMOUNT) AS TOTAL_REVENUE
FROM FACT_SALES F
JOIN DIM_PRODUCT P
    ON F.PRODUCT_ID = P.PRODUCT_ID
GROUP BY P.CATEGORY
ORDER BY TOTAL_REVENUE DESC;

-- Customer Purchase Trend
SELECT C.CUSTOMER_ID, C.CUSTOMER_NAME, D.DATE,
    SUM(F.QUANTITY) AS QUANTITY_PURCHASED,
    SUM(F.TOTAL_AMOUNT) AS PURCHASE_AMOUNT
FROM FACT_SALES F
JOIN DIM_CUSTOMER C
    ON F.CUSTOMER_ID = C.CUSTOMER_ID
JOIN DIM_DATE D
    ON F.DATE_ID = D.DATE_ID
GROUP BY C.CUSTOMER_ID, C.CUSTOMER_NAME, D.DATE
ORDER BY C.CUSTOMER_ID, D.DATE;

-- Product Performance Dashboard
SELECT P.PRODUCT_ID, P.PRODUCT_NAME, P.CATEGORY, P.BRAND,
    COUNT(F.SALE_ID) AS NUMBER_OF_TRANSACTIONS,
    SUM(F.QUANTITY) AS UNITS_SOLD,
    SUM(F.TOTAL_AMOUNT) AS TOTAL_REVENUE,
    AVG(F.TOTAL_AMOUNT) AS AVG_TRANSACTION_VALUE
FROM FACT_SALES F
JOIN DIM_PRODUCT P
    ON F.PRODUCT_ID = P.PRODUCT_ID
GROUP BY P.PRODUCT_ID, P.PRODUCT_NAME, P.CATEGORY, P.BRAND
ORDER BY TOTAL_REVENUE DESC;

-- Branch Performance Dashboard
SELECT B.BRANCH_ID, B.BRANCH_NAME, B.CITY, B.STATE, B.REGION,
    COUNT(F.SALE_ID) AS NUMBER_OF_TRANSACTIONS,
    SUM(F.QUANTITY) AS UNITS_SOLD,
    SUM(F.TOTAL_AMOUNT) AS TOTAL_REVENUE,
    AVG(F.TOTAL_AMOUNT) AS AVG_TRANSACTION_VALUE
FROM FACT_SALES F
JOIN DIM_BRANCH B
    ON F.BRANCH_ID = B.BRANCH_ID
GROUP BY B.BRANCH_ID, B.BRANCH_NAME, B.CITY, B.STATE, B.REGION
ORDER BY TOTAL_REVENUE DESC;

-- Regional Sales Analysis
SELECT B.REGION,
    COUNT(DISTINCT B.BRANCH_ID) AS NUMBER_OF_BRANCHES,
    COUNT(F.SALE_ID) AS NUMBER_OF_TRANSACTIONS,
    SUM(F.QUANTITY) AS TOTAL_UNITS_SOLD,
    SUM(F.TOTAL_AMOUNT) AS TOTAL_REVENUE
FROM FACT_SALES F
JOIN DIM_BRANCH B
    ON F.BRANCH_ID = B.BRANCH_ID
GROUP BY B.REGION
ORDER BY TOTAL_REVENUE DESC;

-- Sales Trend Analysis
SELECT D.DATE,
    SUM(F.QUANTITY) AS TOTAL_QUANTITY,
    SUM(F.TOTAL_AMOUNT) AS TOTAL_REVENUE
FROM FACT_SALES F
JOIN DIM_DATE D
    ON F.DATE_ID = D.DATE_ID
GROUP BY D.DATE
ORDER BY D.DATE;
