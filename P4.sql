/* ---------- 8.24 Top Product in Each Category ---------- */

SELECT
    CATEGORY,
    PRODUCT_ID,
    PRODUCT_NAME,
    TOTAL_REVENUE
FROM (
    SELECT
        P.CATEGORY,
        P.PRODUCT_ID,
        P.PRODUCT_NAME,
        SUM(F.TOTAL_AMOUNT) AS TOTAL_REVENUE,
        ROW_NUMBER() OVER (
            PARTITION BY P.CATEGORY
            ORDER BY SUM(F.TOTAL_AMOUNT) DESC
        ) AS RN
    FROM FACT_SALES F
    JOIN DIM_PRODUCT P
        ON F.PRODUCT_ID = P.PRODUCT_ID
    GROUP BY
        P.CATEGORY,
        P.PRODUCT_ID,
        P.PRODUCT_NAME
)
WHERE RN = 1
ORDER BY CATEGORY;


/* ---------- 8.25 Customers Spending Above Average ---------- */

WITH CUSTOMER_REVENUE AS (
    SELECT
        C.CUSTOMER_ID,
        C.CUSTOMER_NAME,
        SUM(F.TOTAL_AMOUNT) AS TOTAL_REVENUE
    FROM FACT_SALES F
    JOIN DIM_CUSTOMER C
        ON F.CUSTOMER_ID = C.CUSTOMER_ID
    GROUP BY
        C.CUSTOMER_ID,
        C.CUSTOMER_NAME
)
SELECT
    CUSTOMER_ID,
    CUSTOMER_NAME,
    TOTAL_REVENUE
FROM CUSTOMER_REVENUE
WHERE TOTAL_REVENUE > (
    SELECT AVG(TOTAL_REVENUE)
    FROM CUSTOMER_REVENUE
)
ORDER BY TOTAL_REVENUE DESC;

