/* ---------- 7.1 Complete Joined Fact View ---------- */

CREATE OR REPLACE VIEW SALES_DETAIL AS
SELECT
    F.SALE_ID,

    C.CUSTOMER_ID,
    C.CUSTOMER_NAME,
    C.CITY AS CUSTOMER_CITY,
    C.STATE AS CUSTOMER_STATE,
    C.MEMBERSHIP,

    P.PRODUCT_ID,
    P.PRODUCT_NAME,
    P.CATEGORY,
    P.BRAND,
    P.PRICE,

    B.BRANCH_ID,
    B.BRANCH_NAME,
    B.CITY AS BRANCH_CITY,
    B.STATE AS BRANCH_STATE,

    D.DATE_ID,
    D.DATE,
    D.DAY,
    D.DAY_NAME,
    D.WEEK_NO,
    D.MONTH,
    D.QUARTER,
    D.YEAR,
    D.IS_WEEKEND,

    F.QUANTITY,
    F.TOTAL_AMOUNT

FROM FACT_SALES F
JOIN DIM_CUSTOMER C
    ON F.CUSTOMER_ID = C.CUSTOMER_ID
JOIN DIM_PRODUCT P
    ON F.PRODUCT_ID = P.PRODUCT_ID
JOIN DIM_BRANCH B
    ON F.BRANCH_ID = B.BRANCH_ID
JOIN DIM_DATE D
    ON F.DATE_ID = D.DATE_ID;


/* Verify the complete star-schema join */

SELECT *
FROM SALES_DETAIL
ORDER BY SALE_ID;


