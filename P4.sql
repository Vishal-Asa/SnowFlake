    FILE_FORMAT = RETAIL_CSV_FORMAT;




LIST @RETAIL_STAGE;


/* ---------- 2.6 Create Dimension Tables ---------- */

/* Customer Dimension */

CREATE OR REPLACE TABLE DIM_CUSTOMER (
    CUSTOMER_ID      NUMBER(38,0) PRIMARY KEY,
    CUSTOMER_NAME    VARCHAR(100),
    CITY             VARCHAR(100),
    STATE            VARCHAR(100),
    MEMBERSHIP       VARCHAR(50)
);


/* Product Dimension */

CREATE OR REPLACE TABLE DIM_PRODUCT (
    PRODUCT_ID       NUMBER(38,0) PRIMARY KEY,
    PRODUCT_NAME     VARCHAR(100),
    CATEGORY         VARCHAR(100),
    BRAND            VARCHAR(100),
    PRICE            NUMBER(12,2)
);


/* Branch Dimension */

CREATE OR REPLACE TABLE DIM_BRANCH (
    BRANCH_ID        NUMBER(38,0) PRIMARY KEY,
    BRANCH_NAME      VARCHAR(150),
    CITY             VARCHAR(100),
    STATE            VARCHAR(100),
    REGION           VARCHAR(100),
    MANAGER_NAME     VARCHAR(100)
);

/* Date Dimension */

CREATE OR REPLACE TABLE DIM_DATE (
    DATE_ID          NUMBER(38,0) PRIMARY KEY,
    DATE             DATE,
    DAY              NUMBER(2,0),
    DAY_NAME         VARCHAR(20),
    WEEK_NO          NUMBER(2,0),
    MONTH            VARCHAR(20),
    QUARTER          VARCHAR(10),
    YEAR             NUMBER(4,0),
    IS_WEEKEND       VARCHAR(5)
);


/* ---------- 2.7 Create Fact Table ---------- */

CREATE OR REPLACE TABLE FACT_SALES (
    SALE_ID          NUMBER(38,0) PRIMARY KEY,
    CUSTOMER_ID      NUMBER(38,0),
    PRODUCT_ID       NUMBER(38,0),
    BRANCH_ID        NUMBER(38,0),
    DATE_ID          NUMBER(38,0),
    QUANTITY         NUMBER(38,0),
    TOTAL_AMOUNT     NUMBER(14,2),

    CONSTRAINT FK_SALES_CUSTOMER
        FOREIGN KEY (CUSTOMER_ID)
        REFERENCES DIM_CUSTOMER(CUSTOMER_ID),

    CONSTRAINT FK_SALES_PRODUCT
        FOREIGN KEY (PRODUCT_ID)
        REFERENCES DIM_PRODUCT(PRODUCT_ID),

    CONSTRAINT FK_SALES_BRANCH
        FOREIGN KEY (BRANCH_ID)
        REFERENCES DIM_BRANCH(BRANCH_ID),

    CONSTRAINT FK_SALES_DATE
        FOREIGN KEY (DATE_ID)
        REFERENCES DIM_DATE(DATE_ID)
);


