-- Dim State
CREATE OR REPLACE TABLE DIM_STATE (
    STATE_ID NUMBER AUTOINCREMENT,
    STATE_NAME VARCHAR,

    CONSTRAINT PK_DIM_STATE
        PRIMARY KEY (STATE_ID)
);

INSERT INTO DIM_STATE (STATE_NAME)
SELECT DISTINCT STATE
FROM (
    SELECT STATE FROM STG_CUSTOMERS
    UNION
    SELECT STATE FROM STG_BRANCHES
);

-- Dim City
CREATE OR REPLACE TABLE DIM_CITY (
    CITY_ID NUMBER AUTOINCREMENT,
    CITY_NAME VARCHAR,
    STATE_ID NUMBER,

    CONSTRAINT PK_DIM_CITY
        PRIMARY KEY (CITY_ID),

    CONSTRAINT FK_CITY_STATE
        FOREIGN KEY (STATE_ID)
        REFERENCES DIM_STATE(STATE_ID)
);

INSERT INTO DIM_CITY (
    CITY_NAME,
    STATE_ID
)
SELECT DISTINCT
    X.CITY,
    S.STATE_ID
FROM (
    SELECT CITY, STATE
    FROM STG_CUSTOMERS

    UNION

    SELECT CITY, STATE
    FROM STG_BRANCHES
) X
JOIN DIM_STATE S
    ON X.STATE = S.STATE_NAME;

-- Dim Category
CREATE OR REPLACE TABLE DIM_CATEGORY (
    CATEGORY_ID NUMBER AUTOINCREMENT,
    CATEGORY_NAME VARCHAR,

    CONSTRAINT PK_DIM_CATEGORY
        PRIMARY KEY (CATEGORY_ID)
);

INSERT INTO DIM_CATEGORY (CATEGORY_NAME)
SELECT DISTINCT CATEGORY
FROM STG_PRODUCTS;

-- Dim Brand
CREATE OR REPLACE TABLE DIM_BRAND (
    BRAND_ID NUMBER AUTOINCREMENT,
    BRAND_NAME VARCHAR,
    CATEGORY_ID NUMBER,

    CONSTRAINT PK_DIM_BRAND
        PRIMARY KEY (BRAND_ID),

    CONSTRAINT FK_BRAND_CATEGORY
        FOREIGN KEY (CATEGORY_ID)
        REFERENCES DIM_CATEGORY(CATEGORY_ID)
);

INSERT INTO DIM_BRAND (
    BRAND_NAME,
    CATEGORY_ID
)
SELECT DISTINCT
    P.BRAND,
    C.CATEGORY_ID
FROM STG_PRODUCTS P
JOIN DIM_CATEGORY C
    ON P.CATEGORY = C.CATEGORY_NAME;

-- Dim Region
CREATE OR REPLACE TABLE DIM_REGION (
    REGION_ID NUMBER AUTOINCREMENT,
    REGION_NAME VARCHAR,

    CONSTRAINT PK_DIM_REGION
        PRIMARY KEY (REGION_ID)
);

INSERT INTO DIM_REGION (REGION_NAME)
SELECT DISTINCT REGION
FROM STG_BRANCHES;

-- Dim State
ALTER TABLE DIM_STATE
ADD COLUMN REGION_ID NUMBER;

UPDATE DIM_STATE S
SET REGION_ID = R.REGION_ID
FROM (
    SELECT DISTINCT
        STATE,
        REGION
    FROM STG_BRANCHES
) B
JOIN DIM_REGION R
    ON B.REGION = R.REGION_NAME
WHERE S.STATE_NAME = B.STATE;

-- Dim Year
CREATE OR REPLACE TABLE DIM_YEAR (
    YEAR_ID NUMBER AUTOINCREMENT,
    YEAR_VALUE NUMBER,

    CONSTRAINT PK_DIM_YEAR
        PRIMARY KEY (YEAR_ID)
);

INSERT INTO DIM_YEAR (YEAR_VALUE)
SELECT DISTINCT YEAR
FROM STG_CALENDAR;

-- Dim Quarter
CREATE OR REPLACE TABLE DIM_QUARTER (
    QUARTER_ID NUMBER AUTOINCREMENT,
    QUARTER_NAME VARCHAR,
    YEAR_ID NUMBER,

    CONSTRAINT PK_DIM_QUARTER
        PRIMARY KEY (QUARTER_ID),

    CONSTRAINT FK_QUARTER_YEAR
        FOREIGN KEY (YEAR_ID)
        REFERENCES DIM_YEAR(YEAR_ID)
);

INSERT INTO DIM_QUARTER (
    QUARTER_NAME,
    YEAR_ID
)
SELECT DISTINCT
    C.QUARTER,
    Y.YEAR_ID
FROM STG_CALENDAR C
JOIN DIM_YEAR Y
    ON C.YEAR = Y.YEAR_VALUE;

-- Dim Month
CREATE OR REPLACE TABLE DIM_MONTH (
    MONTH_ID NUMBER AUTOINCREMENT,
    MONTH_NAME VARCHAR,
    QUARTER_ID NUMBER,

    CONSTRAINT PK_DIM_MONTH
        PRIMARY KEY (MONTH_ID),

    CONSTRAINT FK_MONTH_QUARTER
        FOREIGN KEY (QUARTER_ID)
        REFERENCES DIM_QUARTER(QUARTER_ID)
);

INSERT INTO DIM_MONTH (
    MONTH_NAME,
    QUARTER_ID
)
SELECT DISTINCT
    C.MONTH,
    Q.QUARTER_ID
FROM STG_CALENDAR C
JOIN DIM_YEAR Y
    ON C.YEAR = Y.YEAR_VALUE
JOIN DIM_QUARTER Q
    ON C.QUARTER = Q.QUARTER_NAME
   AND Q.YEAR_ID = Y.YEAR_ID;

